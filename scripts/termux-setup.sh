#!/usr/bin/env bash
# Install Orbix on an Android phone.
#
# Run this INSIDE Termux — not inside Debian, not on a PC. It creates a Debian
# container with proot-distro and installs Orbix there, because DuckDB and NumPy
# publish glibc (manylinux) ARM64 wheels and Android itself is not glibc. The
# app then runs as a normal Linux server on 127.0.0.1:8000, reachable from the
# phone's own browser.
#
# Usage, from Termux:
#   curl -fsSL <raw url of this file> -o termux-setup.sh
#   bash termux-setup.sh
#
# Overridable: ORBIX_BRANCH, ORBIX_REPO_URL, ORBIX_DIR, ORBIX_DATA_DIR, ORBIX_PORT.
set -eu

REPO_URL="${ORBIX_REPO_URL:-https://github.com/Aizennn7/orbix.git}"
BRANCH="${ORBIX_BRANCH:-main}"
DISTRO="${ORBIX_DISTRO:-debian}"
GUEST_DIR="${ORBIX_DIR:-/root/orbix}"
GUEST_DATA="${ORBIX_DATA_DIR:-/root/orbix-data}"
PORT="${ORBIX_PORT:-8000}"
SERVE_SCRIPT="/root/orbix-serve.sh"

bold() { printf '\n\033[1m%s\033[0m\n' "$*"; }
info() { printf '  %s\n' "$*"; }
die()  { printf '\n\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- sanity checks

case "${PREFIX:-}" in
  *com.termux*) ;;
  *) die "This script must run inside Termux. Install Termux from F-Droid first." ;;
esac

command -v proot-distro >/dev/null 2>&1 || {
  bold "Installing proot-distro"
  pkg install -y proot-distro || die "pkg install failed. Run 'pkg update' once, then retry."
}
command -v curl >/dev/null 2>&1 || {
  bold "Installing curl"
  pkg install -y curl || die "pkg install curl failed."
}

ROOTFS="$PREFIX/var/lib/proot-distro/installed-rootfs/$DISTRO"

# ------------------------------------------------------------ create container

if [ ! -d "$ROOTFS" ]; then
  bold "Creating the Debian container"
  info "About 200 MB will be downloaded. This takes a few minutes."
  proot-distro install "$DISTRO" || die "Could not create the $DISTRO container."
else
  bold "Debian container already present"
fi

# ------------------------------------------------------------ install inside it

bold "Installing Orbix inside Debian"
info "Packages, source, and Python dependencies. Ten minutes on a phone is normal."

proot-distro login "$DISTRO" -- env \
  ORBIX_REPO_URL="$REPO_URL" \
  ORBIX_BRANCH="$BRANCH" \
  ORBIX_DIR="$GUEST_DIR" \
  ORBIX_DATA_DIR="$GUEST_DATA" \
  ORBIX_PORT="$PORT" \
  ORBIX_SERVE="$SERVE_SCRIPT" \
  bash -s <<'GUEST'
set -eu
export DEBIAN_FRONTEND=noninteractive

step() { printf '\n== %s\n' "$*"; }

step "Installing Debian packages"
apt-get update -qq
apt-get install -y -qq --no-install-recommends \
  git ca-certificates python3 python3-venv curl >/dev/null

step "Getting Orbix ($ORBIX_BRANCH)"
if [ -d "$ORBIX_DIR/.git" ]; then
  git -C "$ORBIX_DIR" fetch --depth 1 origin "$ORBIX_BRANCH"
  git -C "$ORBIX_DIR" checkout -q -B "$ORBIX_BRANCH" FETCH_HEAD
  echo "  updated existing checkout"
else
  mkdir -p "$(dirname "$ORBIX_DIR")"
  git clone --quiet --depth 1 --branch "$ORBIX_BRANCH" "$ORBIX_REPO_URL" "$ORBIX_DIR"
  echo "  cloned into $ORBIX_DIR"
fi

step "Installing Python dependencies"
if [ ! -x "$ORBIX_DIR/.venv/bin/python" ]; then
  python3 -m venv "$ORBIX_DIR/.venv"
fi
"$ORBIX_DIR/.venv/bin/pip" install --quiet --upgrade pip
"$ORBIX_DIR/.venv/bin/pip" install --quiet --no-cache-dir -r "$ORBIX_DIR/requirements.txt"

step "Verifying the native wheels"
"$ORBIX_DIR/.venv/bin/python" - <<'PY'
import duckdb, numpy, fastapi, uvicorn
print(f"  duckdb {duckdb.__version__} · numpy {numpy.__version__} · fastapi {fastapi.__version__}")
duckdb.sql("select 1").fetchall()
print("  duckdb query ok")
PY

step "Writing the server launcher"
mkdir -p "$ORBIX_DATA_DIR"
cat > "$ORBIX_SERVE" <<SERVE
#!/usr/bin/env bash
# Generated by scripts/termux-setup.sh. Runs inside the Debian container.
set -eu
cd "$ORBIX_DIR"
export ORBIX_DATA_DIR="$ORBIX_DATA_DIR"
export PYTHONUNBUFFERED=1
exec "$ORBIX_DIR/.venv/bin/python" -m uvicorn orbix.api:app \\
  --host 127.0.0.1 --port "$ORBIX_PORT" --workers 1 --no-server-header
SERVE
chmod +x "$ORBIX_SERVE"

echo
echo "  app     $ORBIX_DIR"
echo "  data    $ORBIX_DATA_DIR"
echo "  python  $("$ORBIX_DIR/.venv/bin/python" --version 2>&1)"
GUEST

[ -f "$ROOTFS$SERVE_SCRIPT" ] || die "The Debian install did not finish. Re-run this script."

# ------------------------------------------------------- Termux-side launchers

bold "Writing the launchers"

cat > "$HOME/orbix-start.sh" <<START
#!/usr/bin/env bash
# Start Orbix and open it in the browser. Safe to run when it is already up.
set -eu
PORT="\${ORBIX_PORT:-$PORT}"
DISTRO="\${ORBIX_DISTRO:-$DISTRO}"
URL="http://127.0.0.1:\$PORT/"
LOG="\$HOME/orbix.log"

termux-wake-lock 2>/dev/null || true

if curl -fsS -m 2 "\${URL}healthz" >/dev/null 2>&1; then
  echo "Orbix is already running."
  termux-open-url "\$URL"
  exit 0
fi

echo "Starting Orbix..."
nohup proot-distro login "\$DISTRO" -- bash $SERVE_SCRIPT >"\$LOG" 2>&1 &
disown 2>/dev/null || true

for _ in \$(seq 1 90); do
  if curl -fsS -m 2 "\${URL}healthz" >/dev/null 2>&1; then
    termux-open-url "\$URL"
    echo "Running at \$URL"
    echo "Log: \$LOG"
    exit 0
  fi
  sleep 1
done

echo "Orbix did not answer within 90 seconds."
echo "Last lines of \$LOG:"
tail -n 30 "\$LOG" 2>/dev/null || true
exit 1
START

cat > "$HOME/orbix-stop.sh" <<STOP
#!/usr/bin/env bash
# Stop the Orbix server.
set -eu
DISTRO="\${ORBIX_DISTRO:-$DISTRO}"
proot-distro login "\$DISTRO" -- pkill -f 'uvicorn orbix.api:app' >/dev/null 2>&1 || true
pkill -f 'uvicorn orbix.api:app' >/dev/null 2>&1 || true
termux-wake-unlock 2>/dev/null || true
echo "Orbix stopped."
STOP

chmod +x "$HOME/orbix-start.sh" "$HOME/orbix-stop.sh"

# Termux:Widget shows anything in ~/.shortcuts on the home screen.
mkdir -p "$HOME/.shortcuts"
for name in start stop; do
  {
    printf '#!%s/bin/bash\n' "$PREFIX"
    printf '# Orbix %s. Tap to run.\n' "$name"
    printf 'exec bash "$HOME/orbix-%s.sh"\n' "$name"
  } > "$HOME/.shortcuts/orbix-$name"
  chmod +x "$HOME/.shortcuts/orbix-$name"
done

bold "Done"
info "Start:  ~/orbix-start.sh"
info "Stop:   ~/orbix-stop.sh"
info "Log:    ~/orbix.log"
info ""
info "Home-screen button: install 'Termux:Widget' from F-Droid, then long-press"
info "your home screen and add the Termux widget; orbix-start appears there."
info ""
info "Next: run  ~/orbix-start.sh"
