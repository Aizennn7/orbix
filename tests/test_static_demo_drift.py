"""Guards the committed GitHub Pages snapshot in docs/ against drift.

docs/ is generated by scripts/build_static_demo.py and committed, because GitHub
Pages serves static files only and the Pages workflow uploads docs/ verbatim with
no build step. Nothing stops someone editing web/app.js and not regenerating,
which would publish a snapshot whose UI silently differs from the app it claims
to show.

The asset list here is deliberately NOT hardcoded. It comes from the builder's
own resolve_asset_closure(), so the guard and the generator cannot drift apart:
if web/index.html grows a new stylesheet or the manifest gains an icon, this test
starts checking it automatically. A previous hand-maintained list of four
"/static/" replacements fell behind index.html (which had seven), and the
snapshot became un-regenerable for days without anything noticing.

Two invariants beyond byte-equality are checked here because both have failed
before:

* Every referenced asset must exist in web/. web/manifest.json used to declare
  two PWA screenshots that were never committed, so the published manifest 404'd
  on both.
* No host filesystem path may appear anywhere in docs/. Captured API responses
  include storage paths, and an unrelated missing re-export once surfaced as an
  error string embedding an absolute path to database/__init__.py. Both leaked
  the build machine's layout into a public site.
"""

from __future__ import annotations

import importlib.util
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "web"
DOCS = ROOT / "docs"
BUILDER = ROOT / "scripts" / "build_static_demo.py"

# Assets copied through unchanged. manifest.json is excluded because the builder
# intentionally rewrites the "/static/" prefixes inside it to relative paths.
TEXT_SUFFIXES = {".json", ".html", ".js", ".css", ".svg", ".txt", ".md", ".map"}


def load_builder():
    """Import scripts/build_static_demo.py without running main().

    The script is not part of a package, so it is loaded by path. Its module
    level is inert (constants and compiled regexes) and main() sits behind an
    `if __name__ == "__main__"` guard, so importing performs no I/O and issues
    no HTTP requests.
    """
    spec = importlib.util.spec_from_file_location("orbix_build_static_demo", BUILDER)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise unittest.SkipTest(f"cannot load {BUILDER}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class StaticDemoDriftTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.builder = load_builder()
        cls.assets = cls.builder.resolve_asset_closure()

    def test_snapshot_was_generated(self) -> None:
        self.assertTrue(
            (DOCS / "index.html").is_file(),
            "docs/index.html is missing. Regenerate with: "
            "python scripts/build_static_demo.py --base-url http://127.0.0.1:8000",
        )
        self.assertTrue(
            (DOCS / ".nojekyll").is_file(),
            "docs/.nojekyll is missing; Pages would skip files starting with '_'.",
        )

    def test_asset_closure_is_not_empty(self) -> None:
        # A silent empty result would make every other assertion vacuous.
        self.assertGreaterEqual(
            len(self.assets),
            4,
            "resolve_asset_closure() found almost nothing; web/index.html parsing "
            "has probably changed shape.",
        )

    def test_every_referenced_asset_exists_in_web(self) -> None:
        missing = [name for name in self.assets if not (WEB / name).is_file()]
        self.assertEqual(
            missing,
            [],
            f"web/index.html or a referenced .json declares assets that do not "
            f"exist, so the published site 404s on them: {missing}",
        )

    def test_every_referenced_asset_was_copied_to_docs(self) -> None:
        missing = [name for name in self.assets if not (DOCS / name).is_file()]
        self.assertEqual(
            missing,
            [],
            f"docs/ is missing generated assets: {missing}. Regenerate with: "
            "python scripts/build_static_demo.py --base-url http://127.0.0.1:8000",
        )

    def test_copied_assets_are_byte_identical(self) -> None:
        drifted = []
        for name in self.assets:
            source, published = WEB / name, DOCS / name
            if not source.is_file() or not published.is_file():
                continue  # reported by the two tests above
            if source.suffix == ".json":
                continue  # rewritten by design; checked separately below
            if source.read_bytes() != published.read_bytes():
                drifted.append(name)
        self.assertEqual(
            drifted,
            [],
            f"docs/ has drifted from web/: {drifted}. Regenerate with: "
            "python scripts/build_static_demo.py --base-url http://127.0.0.1:8000",
        )

    def test_json_assets_are_rewritten_and_valid(self) -> None:
        for name in self.assets:
            published = DOCS / name
            if published.suffix != ".json" or not published.is_file():
                continue
            with self.subTest(asset=name):
                text = published.read_text(encoding="utf-8")
                self.assertNotIn(
                    "/static/",
                    text,
                    f"docs/{name} still points at /static/, which does not exist "
                    "on GitHub Pages.",
                )
                try:
                    json.loads(text)
                except json.JSONDecodeError as exc:  # pragma: no cover - defensive
                    self.fail(f"docs/{name} is not valid JSON: {exc}")

    def test_published_index_has_no_static_prefix(self) -> None:
        text = (DOCS / "index.html").read_text(encoding="utf-8")
        self.assertNotIn(
            "/static/",
            text,
            "docs/index.html still references /static/. The builder rewrites "
            "these; a new reference shape has probably been added to "
            "web/index.html that STATIC_REF does not match.",
        )

    def test_no_host_paths_are_published(self) -> None:
        # Reuse the builder's own pattern so the guard tracks any improvement to
        # it, then add an independent check for this checkout's absolute root in
        # case the pattern is ever too narrow to notice a leak.
        host_path = self.builder.HOST_PATH
        offenders = []
        for path in sorted(DOCS.rglob("*")):
            if not path.is_file() or path.suffix not in TEXT_SUFFIXES:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            hits = set(host_path.findall(text))
            if str(ROOT) in text:
                hits.add(str(ROOT))
            if hits:
                offenders.append(f"{path.relative_to(ROOT)}: {sorted(hits)[:3]}")
        self.assertEqual(
            offenders,
            [],
            "docs/ publishes host filesystem paths. Captured API responses are "
            f"supposed to be scrubbed by redact_paths(): {offenders}",
        )


if __name__ == "__main__":
    unittest.main()
